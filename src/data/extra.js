// 세션에 보강 내용을 붙인다
export function enrich(s, work) {
  const a = EXTRA.common[s.n] || {}, b = (EXTRA[work] && EXTRA[work][s.n]) || {}
  const cat = (k) => [...(a[k] || []), ...(b[k] || [])]
  const hints = { ...(a.hints || {}), ...(b.hints || {}) }
  return {
    ...s,
    learn: cat('learn'),
    tips: cat('tips'),
    safety: cat('safety'),
    more: cat('more'),
    journal: cat('journal'),
    quiz: [...s.quiz, ...cat('quizMore')],
    calc: s.calc ? s.calc.map((c) => (hints[c.id] ? { ...c, hint: hints[c.id] } : c)) : s.calc,
  }
}
